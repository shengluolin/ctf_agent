<?php
// 构造 _GET 的异或组合
// _ = $ ^ { = 36 ^ 123 = 95
// G = : ^ } = 58 ^ 125 = 71
// E = > ^ { = 62 ^ 123 = 69
// T = ) ^ } = 41 ^ 125 = 84

// 字符串1: $:>)
// 字符串2: {{}}
// $ ^ { = _
// : ^ { = 58 ^ 123 = 65 = A (不是 G)

// 重新计算
// 需要两个字符串 s1 和 s2
// s1 ^ s2 = _GET

// s1[0] ^ s2[0] = 95 = _
// s1[1] ^ s2[1] = 71 = G
// s1[2] ^ s2[2] = 69 = E
// s1[3] ^ s2[3] = 84 = T

// 尝试：
// s1 = "$:>)" (36, 58, 62, 41)
// s2[0] = 36 ^ 95 = 123 = { (可用)
// s2[1] = 58 ^ 71 = 121 = y (字母，不可用)

// 尝试其他组合
// s1 = "$:>)" 
// s2[0] = 36 ^ 95 = 123 = {
// s2[1] = 58 ^ 71 = 121 = y (不可用)

// 换 s1
// s1[1] 需要找一个可用字符，使得 s1[1] ^ s2[1] = 71
// 从上面的结果：: ^ } = 71 或 < ^ { = 71

// s1 = "$:<)" 或 "$::)" 或 "$:})" 等
// 测试 "$:})"
// s2[0] = 36 ^ 95 = 123 = {
// s2[1] = 58 ^ 71 = 121 = y (不可用)

// 用 < 代替 :
// s1 = "$<})"
// s2[0] = 36 ^ 95 = 123 = {
// s2[1] = 60 ^ 71 = 115 = s (字母，不可用)

// 用 { 代替
// s1 = "${})"
// s2[0] = 36 ^ 95 = 123 = {
// s2[1] = 123 ^ 71 = 52 = 4 (数字，不可用)

// 需要不同的方法
// 让 s1 和 s2 都用可用字符

// 目标: _GET = 95, 71, 69, 84
// 找两个可用字符序列

// 方法：暴力搜索
$forbidden = "/[\x00- 0-9A-Za-z\'\"\`~_&.,|=[\x7F]+/i";
$allowed = [];
for($i = 33; $i < 127; $i++) {
    $c = chr($i);
    if(!preg_match($forbidden, $c)) {
        $allowed[] = $i;
    }
}

$target = [95, 71, 69, 84];

foreach($allowed as $a0) {
    foreach($allowed as $a1) {
        foreach($allowed as $a2) {
            foreach($allowed as $a3) {
                $s1 = [$a0, $a1, $a2, $a3];
                $s2 = [];
                $valid = true;
                for($i = 0; $i < 4; $i++) {
                    $c = $s1[$i] ^ $target[$i];
                    if(!in_array($c, $allowed)) {
                        $valid = false;
                        break;
                    }
                    $s2[] = $c;
                }
                if($valid) {
                    echo "s1: " . chr($a0).chr($a1).chr($a2).chr($a3) . "\n";
                    echo "s2: " . chr($s2[0]).chr($s2[1]).chr($s2[2]).chr($s2[3]) . "\n";
                    echo "s1 ^ s2 = " . chr($a0 ^ $s2[0]).chr($a1 ^ $s2[1]).chr($a2 ^ $s2[2]).chr($a3 ^ $s2[3]) . "\n\n";
                }
            }
        }
    }
}
?>
